const planted = "Test Author, 1 Secret Road"

func TestElementsOutsideTheStandardGo(t *testing.T) {
	for name, body := range map[string]string{
		"unknown SVG element":  `<creator>` + planted + `</creator>`,
		"wrong case":           `<Metadata>` + planted + `</Metadata>`,
		"no namespace":         `<foo xmlns="">` + planted + `</foo>`,
		"xml namespace":        `<xml:creator>` + planted + `</xml:creator>`,
		"xlink namespace":      `<xlink:creator>` + planted + `</xlink:creator>`,
		"events namespace":     `<ev:creator xmlns:ev="http://www.w3.org/2001/xml-events">` + planted + `</ev:creator>`,
		"attribute of unknown": `<creator name="` + planted + `"/>`,
		"nested in an unknown": `<foo><rect/><bar>` + planted + `</bar></foo>`,
	} {
		t.Run(name, func(t *testing.T) {
			data := svgDoc(`<rect/>` + body + `<circle r="1"/>`)
			out, rep := clean(t, data, core.Options{})
			if strings.Contains(out, planted) {
				t.Error("the planted text survived")
			}
			if len(rep.Residual()) == 0 {
				t.Error("nothing was reported")
			}
			if !strings.Contains(out, `<rect/>`) || !strings.Contains(out, `<circle r="1"/>`) {
				t.Errorf("real content went: %s", out)
			}
			if again, _ := clean(t, out, core.Options{}); again != out {
				t.Error("a second clean changed the file")
			}
		})
	}
}

