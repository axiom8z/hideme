// Hostile shapes: these must finish quickly however long the file is.
func TestScanTimeStaysLinear(t *testing.T) {
	var manyAttrs strings.Builder
	manyAttrs.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" `)
	for i := range 200000 {
		fmt.Fprintf(&manyAttrs, "a%d=\"1\" ", i)
	}
	manyAttrs.WriteString(">")
	manyAttrs.WriteString(strings.Repeat("<g/>", 200000))
	manyAttrs.WriteString("</svg>")

	nested := `<svg xmlns="http://www.w3.org/2000/svg">` +
		strings.Repeat(strings.Repeat("<title>", 2000)+strings.Repeat("</title>", 2000), 300) + `</svg>`

	var bindings strings.Builder
	bindings.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:first="http://www.w3.org/1999/xlink" `)
	for i := range maxBindings - 3 {
		fmt.Fprintf(&bindings, `xmlns:p%d="http://www.w3.org/1999/xlink" `, i)
	}
	bindings.WriteString(">")
	bindings.WriteString(strings.Repeat(`<g first:href="#a"/>`, 500000))
	bindings.WriteString("</svg>")

	var metadata strings.Builder
	metadata.WriteString(`<svg xmlns="http://www.w3.org/2000/svg" `)
	for i := range maxBindings - 2 {
		fmt.Fprintf(&metadata, `xmlns:p%d="http://www.w3.org/2000/svg" `, i)
	}
	metadata.WriteString(">")
	metadata.WriteString(strings.Repeat(`<metadata/>`, maxFindings))
	metadata.WriteString("</svg>")

	for name, data := range map[string]string{
		"a huge tag, then many small ones": manyAttrs.String(),
		"titles nested in titles":          nested,
		"many lookups of a distant prefix": bindings.String(),
		"many metadata elements":           metadata.String(),
	} {
		t.Run(name, func(t *testing.T) {
			start := time.Now()
			_, _, err := analyse(t.Context(), core.BytesSource([]byte(data)), core.Options{})
			if err != nil {
				t.Fatal(err)
			}
			if took := time.Since(start); took > 10*time.Second {
				t.Errorf("%d bytes took %v", len(data), took)
			}
		})
	}
}

