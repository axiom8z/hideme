func TestNestedTitlesAreReported(t *testing.T) {
	data := svgDoc(`<g><title>` + planted + `</title><desc>Test Description</desc><rect/></g>`)
	out, rep := clean(t, data, core.Options{})
	if out != data {
		t.Errorf("a nested title changed: %s", out)
	}
	if !hasField(rep, "Title", core.ActionRetain) || !hasField(rep, "Description", core.ActionRetain) {
		t.Errorf("nested text went unreported: %+v", rep.Findings)
	}
	out, rep = clean(t, data, core.Options{Strict: true})
	if strings.Contains(out, planted) || strings.Contains(out, "Test Description") {
		t.Error("Strict kept nested text")
	}
	if !hasField(rep, "Title", core.ActionRemove) {
		t.Errorf("findings: %+v", rep.Findings)
	}
	out, _ = clean(t, svgDoc(`<g><desc>Created with Test Tool</desc></g>`), core.Options{})
	if strings.Contains(out, "Test Tool") {
		t.Error("a nested tool banner survived")
	}
}

