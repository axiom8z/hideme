// xmlTokens lists what a conforming XML parser, given the entities, sees in a file. An
// independent parser accepting the output is the point.
func xmlTokens(t *testing.T, data string, entities map[string]string) []xml.Token {
	t.Helper()
	d := xml.NewDecoder(strings.NewReader(data))
	d.Entity = entities
	var out []xml.Token
	for {
		tok, err := d.Token()
		if err == io.EOF {
			return out
		}
		if err != nil {
			t.Fatalf("encoding/xml: %v", err)
		}
		out = append(out, xml.CopyToken(tok))
	}
}

