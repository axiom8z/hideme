// wrappedBase64 wraps at 76 columns with character references, as Inkscape does.
func wrappedBase64(s string) string {
	encoded := base64.StdEncoding.EncodeToString([]byte(s))
	var b strings.Builder
	for len(encoded) > 8 {
		b.WriteString(encoded[:8])
		b.WriteString("&#10;")
		encoded = encoded[8:]
	}
	b.WriteString(encoded)
	return b.String()
}

