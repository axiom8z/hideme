// Whether a data- attribute stays must depend on what stays in the file, not on what was
// in it: otherwise a second clean would remove what the first kept, and the engine, which
// checks the output, would refuse the file. Every file from Illustrator's XMP has the word
// Description in it, which holds the word script.
func TestDataAttributeDecisionSurvivesASecondClean(t *testing.T) {
	for name, data := range map[string]string{
		"a word in removed metadata": svgDoc(`<metadata><rdf:Description xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"/></metadata><g data-name="` + planted + `"/>`),
		"a word in a comment":        svgDoc(`<!-- script --><g data-name="` + planted + `"/>`),
		"a selector in a comment":    svgDoc(`<!-- [data-name] --><g data-name="` + planted + `"/>`),
		"a removed attribute":        svgDoc(`<g author="script" data-name="` + planted + `"/>`),
		"a removed element":          svgDoc(`<script xmlns="http://example.com/x">1</script><g data-name="` + planted + `"/>`),
	} {
		t.Run(name, func(t *testing.T) {
			out, rep := clean(t, data, core.Options{})
			if strings.Contains(out, planted) {
				t.Errorf("the data attribute stayed: %s", out)
			}
			if again, second := clean(t, out, core.Options{}); again != out || len(second.Residual()) != 0 {
				t.Errorf("a second clean gave %s, findings %+v", again, second.Findings)
			}
			if slices.ContainsFunc(rep.Warnings, func(w string) bool { return strings.Contains(w, "data-") }) {
				t.Errorf("warnings = %q", rep.Warnings)
			}
		})
	}
	data := svgDoc(`<script>1</script><g data-name="` + planted + `"/>`)
	out, _ := clean(t, data, core.Options{})
	if again, _ := clean(t, out, core.Options{}); again != out || !strings.Contains(out, planted) {
		t.Errorf("a data attribute in use: %s then %s", out, again)
	}
}

